    "VehicleKey", string(vehicleKey), ...
    "DisplayName", string(displayName), ...
    "VehiclePath", string(vehiclePath), ...
    "SetupFunction", string(setupFunction), ...
    "BusFunction", string(busFunction), ...
    "PlantModel", string(plantModel), ...
    "PX4Target", string(px4Target), ...
