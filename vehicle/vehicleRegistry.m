function vehicle = makeVehicle(vehicleKey, displayName, vehiclePath, setupFunction, busFunction, ...
    plantModel, px4Target, controllerType, actuatorInterface, supportsWaypoints, ...
    supportsFlightGear, supportsGazebo, testTimeoutSeconds, aliases, baseVehicleType, ...
    compileModel, testDefinition)

